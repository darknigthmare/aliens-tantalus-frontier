export function validateWeaponResearchIndexV171(rows=WEAPON_RESEARCH_INDEX_V171) {
 const errors=[],seen=new Set();
 for(const row of rows){
   if(!/^proposed-[a-z0-9-]+$/.test(row.id)||seen.has(row.id))
     errors.push('invalid-or-duplicate:'+row.id);
   seen.add(row.id);
   if(!row.name||!row.work||!['P0','P1','P2'].includes(row.priority))
     errors.push('missing-fields:'+row.id);
   if(row.sourceUrl && !/^https:\/\//.test(row.sourceUrl))errors.push('invalid-link:'+row.id);
   if(row.admission!=='RESEARCH_ONLY'||row.canonExact!==false)
     errors.push('invented-admission:'+row.id);
 }
 return { valid:errors.length===0,errors,proposed:rows.length,
  p0:rows.filter(x=>x.priority==='P0').length,
  p1:rows.filter(x=>x.priority==='P1').length,
  p2:rows.filter(x=>x.priority==='P2').length,
  media:[...new Set(rows.map(x=>x.work))].length,
  plausibleExactNameMatches:rows.filter(row=>exactCatalogNames.has(normalize(row.name))).length };
}
