let writesV143 = Promise.resolve();
function retainResponseV143(request, response) {
  // Serialize pruning so simultaneous image loads cannot evict shell entries or
  // turn quota/write errors into unhandled rejections in the gameplay request.
  writesV143 = writesV143.catch(() => {}).then(async () => {
    const cache = await caches.open(CACHE);
    if (!cacheableResponseV143(request, response)) { await cache.delete(request); return; }
    await cache.put(request, response);
    const extra = (await cache.keys()).filter(key => !SHELL_PATHS.has(new URL(key.url).pathname));
    for (const key of extra.slice(0, Math.max(0, extra.length - MAX_RUNTIME_ENTRIES_V143))) await cache.delete(key);
  }).catch(() => {});
  return writesV143;
}

async function precacheV143() {
  const cache = await caches.open(CACHE);
  // Bounded requests and an all-or-nothing install. A missing critical module,
  // private response or HTML fallback leaves the previous worker active.
  let next = 0, failed = false;
  const workers = Array.from({ length: Math.min(6, SHELL.length) }, async () => {
    while (next < SHELL.length && !failed) {
      const path = SHELL[next++];
      const request = new Request(new URL(path, self.location.origin), { credentials: 'omit', cache: 'reload' });
      try {
        const response = await fetch(request);
        if (!cacheableResponseV143(request, response)) throw new Error(`Invalid offline resource: ${path}`);
        await cache.put(request, response);
      } catch (error) { failed = true; throw error; }
    }
  });
  const results = await Promise.allSettled(workers);
  const rejected = results.find(result => result.status === 'rejected');
  if (rejected) { await caches.delete(CACHE); throw rejected.reason; }
}

