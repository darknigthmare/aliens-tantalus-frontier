import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { promisify } from 'node:util';
import { XENO_TRIALS_FIGHTERS_V96, XENO_TRIALS_STAGES_V96, getXenoTrialsArtV96 } from '../src/xeno-trials-data-v96.js';

const execute = promisify(execFile);
const output = 'assets/openai/xeno-trials-menu-v222';
const env = { ...process.env, MAGICK_THREAD_LIMIT: '2' };
const convert = args => execute('magick', args, { env });
const asRect = (bounds) => {
  if (!Array.isArray(bounds) || bounds.length !== 4 || !bounds.every(Number.isInteger)) return null;
  const [left, top, right, bottom] = bounds;
  return right > left && bottom > top ? [left, top, right - left, bottom - top] : null;
};
const stageCrop = stage => {
  const atlas = stage.atlasV192;
  if (atlas) return atlas.sourceRects?.[0] ?? [0, 0, atlas.width, Math.floor(atlas.height / 3)];
  return null;
};

const groups = {
  fighter: { width: 112, height: 112, columns: 16, rows: XENO_TRIALS_FIGHTERS_V96.flatMap(fighter =>
    [null, ...fighter.variants].map(variant => {
      const art = getXenoTrialsArtV96(fighter.id, variant);
      return { id: variant ? `${fighter.id}:${variant}` : fighter.id, source: art.path, crop: asRect(art.alphaBounds) };
    })) },
  stage: { width: 144, height: 81, columns: 12, rows: XENO_TRIALS_STAGES_V96.filter(stage => stage.backdrop).map(stage =>
    ({ id: stage.id, source: stage.backdrop, crop: stageCrop(stage), corporateAtlas: stage.stageRevision === 190 })) },
};

await mkdir(output, { recursive: true });
const temp = await mkdtemp(join(tmpdir(), 'xeno-trials-thumbnails-'));
const atlases = {};
try {
  for (const [kind, { width, height, columns, rows }] of Object.entries(groups)) {
    const paths = rows.map((_, index) => join(temp, `${kind}-${index}.png`));
    const extent = `${width}x${height}`;
    const chunkSize = 6;
    for (let first = 0; first < rows.length; first += chunkSize) {
      await Promise.all(rows.slice(first, first + chunkSize).map(({ source, crop, corporateAtlas }, index) => {
        assert.ok(/^\/assets\/[\w/.-]+\.(?:png|webp|jpe?g)$/iu.test(source), source);
        const cropped = crop ? ['-crop', `${crop[2]}x${crop[3]}+${crop[0]}+${crop[1]}`, '+repage']
          : corporateAtlas ? ['-crop', '100%x33.333333%+0+0', '+repage'] : [];
        const shape = kind === 'fighter'
          ? ['-resize', '106x106', '-gravity', 'South'] : ['-resize', `${extent}^`, '-gravity', 'Center'];
        return convert([`${source.slice(1)}[0]`, ...cropped, ...shape, '-background', 'none', '-extent', extent, paths[first + index]]);
      }));
    }
    const path = `${output}/${kind}.webp`;
    await convert(['montage', ...paths, '-tile', `${columns}x`, '-geometry', `${extent}+0+0`, '-background', 'none',
      '-quality', '77', '-define', 'webp:method=6', path]);
    const bytes = await readFile(path);
    atlases[kind] = { path: `/${path}`, width, height, columns, sha256: createHash('sha256').update(bytes).digest('hex'),
      ids: rows.map(row => row.id) };
    console.log(`${kind}: ${rows.length} tiles, ${bytes.length} bytes`);
  }
  await writeFile('src/xeno-trials-menu-atlases-v222.js',
    `// Generated by scripts/generate-xeno-trials-menu-media-v222.mjs.\nexport const XENO_TRIALS_MENU_ATLASES_V222 = ${JSON.stringify(atlases, null, 2)};\n`);
} finally {
  await rm(temp, { recursive: true, force: true });
}
