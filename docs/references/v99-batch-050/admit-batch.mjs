// Deterministic admission only: no generation or modification of native pixels.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { auditPngBuffer } from '../v91-enemy-only/audit-candidate-png.mjs';
const here = new URL('./', import.meta.url), root = new URL('../../../', here);
const json = path => JSON.parse(readFileSync(new URL(path, here), 'utf8'));
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const batch = json('batch-050.json');
const shards = ['a', 'b', 'c'].map(s => json(`shard-${s}.json`));
const accepted = shards.flatMap(s => Array.isArray(s.accepted) ? s.accepted : s.poses);
const heldIds = shards.flatMap(s => s.held).map(h => typeof h === 'string' ? h : h.profileId);
const jobs = new Map(batch.jobs.map(j => [j.profileId, j]));
assert.equal(batch.jobs.length, 50);
assert.equal(new Set([...accepted.map(p => p.profileId), ...heldIds]).size, 50);
assert.equal(accepted.length + heldIds.length, 50);
assert.ok(heldIds.every(id => jobs.has(id)));
const outcomes = [];
for (const job of batch.jobs) {
  const receipt = json(`generation-${job.profileId}.json`);
  assert.equal(receipt.profileId, job.profileId);
  assert.equal(receipt.reference.sha256, job.referenceSha256);
  assert.equal(hash(readFileSync(new URL(job.referencePath, root))), job.referenceSha256);
  const pose = accepted.find(p => p.profileId === job.profileId);
  if (!pose) {
    assert.ok(heldIds.includes(job.profileId)); assert.match(receipt.review.status, /held|reject/);
    outcomes.push({ ordinal: job.ordinal, profileId: job.profileId, status: 'held', reason: receipt.review.notes });
    continue;
  }
  assert.match(receipt.review.status, /^accepted/);
  assert.equal(pose.id, job.profileId); assert.equal(pose.path, `/${job.outputPath}`); assert.equal(pose.sourceFacing, 1);
  assert.ok(pose.pivot.x >= 0 && pose.pivot.x <= 1 && pose.pivot.y > 0 && pose.pivot.y <= 1);
  assert.deepEqual(pose.pivot, receipt.runtimeContract.pivot);
  assert.equal(pose.targetOpaqueHeight, job.targetOpaqueHeight);
  const bytes = readFileSync(new URL(job.outputPath, root)), alpha = auditPngBuffer(bytes);
  assert.equal(hash(bytes), pose.sha256); assert.equal(receipt.output.sha256, pose.sha256);
  assert.deepEqual([alpha.width, alpha.height], [pose.sourceWidth, pose.sourceHeight]);
  assert.deepEqual(alpha.bboxAlphaAtLeast16, pose.alphaBounds); assert.equal(alpha.alphaMin, 0);
  assert.ok(alpha.alpha0 / alpha.totalPixels > .2);
  assert.ok(pose.alphaBounds[0] > 0 && pose.alphaBounds[1] > 0 && pose.alphaBounds[2] < pose.sourceWidth && pose.alphaBounds[3] < pose.sourceHeight);
  outcomes.push({ ordinal: job.ordinal, profileId: job.profileId, status: 'accepted-static-pose', path: pose.path,
    sha256: pose.sha256, bioforgeEligible: job.profileId !== 'enemy-207-acid-blooded-ceto-reef-predator' });
}
accepted.sort((a, b) => jobs.get(a.profileId).ordinal - jobs.get(b.profileId).ordinal);
writeFileSync(new URL('src/enemy-dedicated-batch-v99.js', root),
  '// Generated by docs/references/v99-batch-050/admit-batch.mjs. Native pixels unchanged.\n'
  + '// Static systemic project variants, not animation or canonical certification.\n'
  + `export const ENEMY_DEDICATED_BATCH_V99 = Object.freeze(${JSON.stringify(accepted, null, 2)}.map(record => Object.freeze(record)));\n`);
writeFileSync(new URL('ADMISSION.json', here), JSON.stringify({ schema: 99, date: '2026-09-27', attempted: 50,
  accepted: accepted.length, held: heldIds.length, priorHoldsUnchanged: 34, animation: false, canonExact: false,
  outcomes }, null, 2) + '\n');
console.log(JSON.stringify({ attempted: 50, accepted: accepted.length, held: heldIds.length }));
